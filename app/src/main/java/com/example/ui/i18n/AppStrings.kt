    fun formatSyncState(code: String, working: Int, total: Int, errorDetail: String): String = when (code) {
        SyncStateCode.WORKING -> syncStateWorking(working, total)
        SyncStateCode.NONE_WORKING -> syncStateNoneWorking(total)
        SyncStateCode.ERROR -> syncStateError(errorDetail)
        else -> syncStateIdle
    }

    fun formatDownloadError(reasonKey: String, detail: String): String = when (reasonKey) {
        "untrusted_source" -> downloadErrUntrusted
        "apk_signature_mismatch" -> downloadErrSignature
        "apk_package_mismatch" -> downloadErrPackage
        "apk_downgrade_blocked" -> downloadErrDowngrade
        "apk_corrupt", "empty_file" -> downloadErrCorrupt
        else -> downloadErrGeneric(detail)
    }
}

